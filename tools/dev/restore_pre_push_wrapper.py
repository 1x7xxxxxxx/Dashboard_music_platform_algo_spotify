#!/usr/bin/env python3
"""Put the fleet's pre-push wrapper back after `pre-commit install` moved it aside (R705).

Type: Utility
Uses: the hook path given as argv[1], and `<hook>.legacy` beside it
Triggers: `make hooks-install`, right after `pre-commit install`
Persists in: .git/hooks/pre-push

`pre-commit install` does not recognise the wrapper as its own script, so it moves it to
`pre-push.legacy` and writes the bare framework hook. The framework then runs the legacy
file under PRE_COMMIT_RUNNING_LEGACY, where the wrapper exits at once: pushes still pass
their gates, but no verdict reaches gate-timings, and nothing says so.

The wrapper must NOT carry the framework's `# File generated by pre-commit` header: the
installer would then overwrite it in place, leaving no `.legacy` to restore from.
"""
import re
import sys
from pathlib import Path

MARK = "fleet-apply pre-push wrapper (T406b)"
TEMPLATED = re.compile(r"# start templated\n.*?# end templated\n", re.S)


def restore(hook: Path) -> str:
    """Return what was done: 'in-place', 'nothing-to-restore', 'no-template' or 'restored'."""
    current = hook.read_text(encoding="utf-8") if hook.exists() else ""
    if MARK in current:
        return "in-place"
    legacy = hook.with_name(hook.name + ".legacy")
    wrapper = legacy.read_text(encoding="utf-8") if legacy.exists() else ""
    if MARK not in wrapper:
        return "nothing-to-restore"
    fresh = TEMPLATED.search(current)
    if fresh is None or not TEMPLATED.search(wrapper):
        return "no-template"
    hook.write_text(TEMPLATED.sub(lambda _: fresh.group(0), wrapper, count=1), encoding="utf-8")
    hook.chmod(0o755)
    legacy.unlink()
    return "restored"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: restore_pre_push_wrapper.py <path of hooks/pre-push>", file=sys.stderr)
        return 2
    outcome = restore(Path(argv[1]))
    print(f"pre-push wrapper: {outcome}")
    return 1 if outcome == "no-template" else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
